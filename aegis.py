    def _render_poly(self, voices, volume=0.22, sr=22050):
        try:
            total_ms = 0
            for delay_ms, seq in voices: total_ms = max(total_ms, delay_ms + sum(d for _, d, _ in seq))
            if total_ms <= 0: return None
            total_samples = int(sr * total_ms / 1000) + 1
            buffer = [0.0] * total_samples
            for delay_ms, seq in voices:
                pos = int(sr * delay_ms / 1000)
                for freq, dur_ms, kind in seq:
                    if kind == "sine": h = [(1.0, 1.0)]
                    elif kind == "rich": h = [(1.0, 1.0), (2.0, 0.35), (3.0, 0.15)]
                    elif kind == "bell": h = [(1.0, 1.0), (2.76, 0.30), (5.4, 0.12)]
                    elif kind == "square": h = [(1.0, 1.0), (3.0, 0.33), (5.0, 0.20)]
                    elif kind == "bass": h = [(0.5, 0.8), (1.0, 1.0), (2.0, 0.3)]
                    else: h = [(1.0, 1.0)]
                    n = int(sr * dur_ms / 1000)
                    if n < 1: continue
                    fi = max(1, n // 20); fo = max(1, n // 6)
                    for i in range(n):
                        if i < fi: env = i / fi
                        elif i > n - fo: env = (n - i) / fo
                        else: env = 1.0
                        s = sum(w * math.sin(2 * math.pi * freq * r * i / sr) for r, w in h) * env
                        idx = pos + i
                        if 0 <= idx < total_samples: buffer[idx] += s
                    pos += n
            peak = max(abs(x) for x in buffer) if buffer else 0
            scale = (volume * 32767) / peak if peak > 0 else 0
            frames = bytearray()
            for x in buffer:
                v = int(x * scale); v = max(-32768, min(32767, v))
                frames += struct.pack("<h", v)
            fd, path = tempfile.mkstemp(suffix=".wav", prefix="aegis_"); os.close(fd)
            self._temp_files.append(path)
            with wave.open(path, "w") as w:
                w.setnchannels(1); w.setsampwidth(2); w.setframerate(sr); w.writeframes(bytes(frames))
            return path
        except Exception: return None
