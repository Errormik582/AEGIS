    def play(self, name, loop=False):
        if not self.enabled: return
        if self.backend == "pygame":
            snd = self._pygame_sounds.get(name)
            if not snd: return
            try:
                if name.startswith("music"):
                    if self._music_channel is None: self._music_channel = self.pygame.mixer.Channel(0)
                    self._music_channel.stop(); self._music_channel.play(snd, loops=-1, fade_ms=600)
                    self.music_playing = True; self._current_music = name
                else: snd.play()
            except Exception: pass
        elif self.backend == "winsound":
            path = self.sounds.get(name)
            if not path: return
            if self.music_playing and not name.startswith("music"): return
            try:
                flags = self.winsound.SND_FILENAME | self.winsound.SND_ASYNC
                if loop: flags |= self.winsound.SND_LOOP
                self.winsound.PlaySound(path, flags)
                if name.startswith("music"):
                    self.music_playing = True; self._current_music = name
            except Exception: pass
